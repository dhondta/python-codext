# module placement (ISO 16022 Annex F / datamatrix-svg)
_NOMINAL = [0, 0, -1, 0, -2, 0, 0, -1, -1, -1, -2, -1, -1, -2, -2, -2]


def _positions(w, h, nc, nr, bc):
    """ For each codeword, the 8 (row, column) module coordinates of its bits (bit 0 first). """
    fw, fh = w // nc, h // nr
    positions, s, c, r, i = [], 2, 0, 4, 0
    while i < bc:
        if r == h - 3 and c == -1:
            k = [w, 6-h, w, 5-h, w, 4-h, w, 3-h, w-1, 3-h, 3, 2, 2, 2, 1, 2]
        elif r == h + 1 and c == 1 and (w & 7) == 0 and (h & 7) == 6:
            k = [w-2, -h, w-3, -h, w-4, -h, w-2, -1-h, w-3, -1-h, w-4, -1-h, w-2, -2, -1, -2]
        else:
            if r == 0 and c == w - 2 and (w & 3):
                r -= s
                c += s
                continue
            if r < 0 or c >= w or r >= h or c < 0:
                s = -s
                r += 2 + s // 2
                c += 2 - s // 2
                while r < 0 or c >= w or r >= h or c < 0:
                    r -= s
                    c += s
            if r == h - 2 and c == 0 and (w & 3):
                k = [w-1, 3-h, w-1, 2-h, w-2, 2-h, w-3, 2-h, w-4, 2-h, 0, 1, 0, 0, 0, -1]
            elif r == h - 2 and c == 0 and (w & 7) == 4:
                k = [w-1, 5-h, w-1, 4-h, w-1, 3-h, w-1, 2-h, w-2, 2-h, 0, 1, 0, 0, 0, -1]
            elif r == 1 and c == w - 1 and (w & 7) == 0 and (h & 7) == 6:
                r -= s
                c += s
                continue
            else:
                k = _NOMINAL
        bits = []
        for j in range(0, 16, 2):
            x, y = c + k[j], r + k[j+1]
            if x < 0:
                x += w
                y += 4 - ((w + 4) & 7)
            if y < 0:
                y += h
                x += 4 - ((h + 4) & 7)
            bits.append((y + 2 * (y // fh) + 1, x + 2 * (x // fw) + 1))
        positions.append(bits)
        i += 1
        r -= s
        c += s
    return positions


def _finder(grid, w, h, nc, nr):
    fw, fh = w // nc, h // nr
    for i in range(0, h + 2 * nr, fh + 2):
        for j in range(0, w + 2 * nc):
            grid[i + fh + 1][j] = 1
            if j & 1 == 0:
                grid[i][j] = 1
    for i in range(0, w + 2 * nc, fw + 2):
        for j in range(h):
            grid[j + (j // fh) * 2 + 1][i] = 1
            if j & 1 == 1:
                grid[j + (j // fh) * 2][i + fw + 1] = 1


def _encode_dc(dc, rect):
    w, h, nc, nr, bc, s, b = _choose(len(dc), rect)
    cw = _codewords(dc, bc, s, b)
    grid = [[0] * (w + 2 * nc) for _ in range(h + 2 * nr)]
    _finder(grid, w, h, nc, nr)
    for idx, bits in enumerate(_positions(w, h, nc, nr, bc)):
        v = cw[idx]
        for j, (y, x) in enumerate(bits):
            if (v >> j) & 1:
                grid[y][x] = 1
    # the fixed bottom-right unfilled corner (for symbols whose width is not a multiple of 4)
    i = w
    while i & 3:
        grid[i][i] = 1
        i -= 1
    return grid


def _encode(data, rect):
    return _encode_dc(_encode_data(data), rect)


