# symbol geometry and Reed-Solomon
def _geometries():
    geoms = []
    k = [5, 7, 10, 12, 14, 18, 20, 24, 28, 36, 42, 48, 56, 68, 84, 112, 144, 192, 224, 272, 336, 408, 496, 620]
    w = h = 6
    i = 2
    for j in range(len(k)):
        if w > 11 * i:
            i = 4 + i & 12
        h += i
        w = h
        bc = (w * h) >> 3
        nr = nc = 2 * (w // 54) + 2 if w > 27 else 1
        b = 2 * (bc >> 9) + 2 if bc > 255 else 1
        geoms.append((w, h, nc, nr, bc, k[j], b, False))
    kr = [16, 7, 28, 11, 24, 14, 32, 18, 32, 24, 44, 28]
    for j in range(0, 12, 2):
        w, hh = kr[j], 6 + (j & 12)
        bc = w * hh // 8
        nc = 2 if w > 25 else 1
        geoms.append((w, hh, nc, 1, bc, kr[j+1], 1, True))
    return geoms


_GEOMS = _geometries()
_BY_SIZE = {(h + 2 * nr, w + 2 * nc): (w, h, nc, nr, bc, s, b) for (w, h, nc, nr, bc, s, b, _) in _GEOMS}
_SIZES = sorted({r for r, _ in _BY_SIZE})


def _choose(el, rect):
    for (w, h, nc, nr, bc, s, b, r) in _GEOMS:
        if r != bool(rect):
            continue
        if rect and el >= 50:
            break
        if bc - s >= el:
            return w, h, nc, nr, bc, s, b
    if rect:
        return _choose(el, False)
    raise ValueError("'datamatrix' codec can't encode input of more than %d bytes" % (_GEOMS[23][4] - _GEOMS[23][5]))


def _rs_encode_block(data, nc):
    log, exp, x = [0] * 256, [0] * 255, 1
    for i in range(255):
        exp[i] = x
        log[x] = i
        x <<= 1
        if x > 255:
            x ^= _PP
    gen = [0] * (nc + 1)
    gen[nc] = 0
    for i in range(1, nc + 1):
        gen[nc - i] = 1
        for j in range(nc - i, nc):
            gen[j] = gen[j+1] ^ exp[(log[gen[j]] + i) % 255]
    rc = [0] * (nc + 1)
    for d in data:
        x = rc[0] ^ d
        for j in range(nc):
            rc[j] = rc[j+1] ^ (exp[(log[gen[j]] + log[x]) % 255] if x else 0)
    return rc[:nc]


def _codewords(data_cw, bc, s, b):
    """ Pad the data codewords and append the interleaved Reed-Solomon codewords. """
    enc = list(data_cw)
    if len(enc) < bc - s:
        enc.append(129)
    while len(enc) < bc - s:
        enc.append((((149 * (len(enc) + 1)) % 253) + 130) % 254)
    nc = s // b
    ec = [0] * s
    for c in range(b):
        block = enc[c::b]
        for i, v in enumerate(_rs_encode_block(block, nc)):
            ec[c + i * b] = v
    return enc + ec


