# decoding: codewords -> data bytes (every encodation scheme)
def _decode_text(cw, i, basic, set3, x12):
    vals = []
    while i < len(cw):
        if cw[i] == 254:
            i += 1
            break
        if i + 1 >= len(cw):
            break  # pragma: no cover
        word = (cw[i] << 8) + cw[i+1] - 1
        i += 2
        vals += [word // 1600, (word // 40) % 40, word % 40]
    out = bytearray()
    if x12:
        for v in vals:
            out.append(ord(_X12[v]))
    else:
        shift = 0
        for v in vals:
            if shift == 0:
                if v < 3:
                    shift = v + 1
                else:
                    out.append(ord(basic[v - 3]))
            else:
                out.append(ord((_SET1, _SET2, set3)[shift - 1][v]))
                shift = 0
    return i, bytes(out)


def _decode_edifact(cw, i):
    out = bytearray()
    while i + 2 < len(cw):
        word = (cw[i] << 16) + (cw[i+1] << 8) + cw[i+2]
        i += 3
        vals = [(word >> 18) & 0x3F, (word >> 12) & 0x3F, (word >> 6) & 0x3F, word & 0x3F]
        done = False
        for v in vals:
            if v == 0x1F:
                done = True
                break
            out.append(v if v >= 0x20 else v | 0x40)
        if done:
            break
    return i, bytes(out)


def _decode_base256(cw, i, n):
    unrand = lambda byte, pos: (byte - (((149 * pos) % 255) + 1)) % 256
    d1 = unrand(cw[i], i + 1)
    i += 1
    if d1 == 0:
        length = n - i
    elif d1 < 250:
        length = d1
    else:
        length = 250 * (d1 - 249) + unrand(cw[i], i + 1)  # pragma: no cover
        i += 1  # pragma: no cover
    out = bytearray()
    for _ in range(length):
        if i >= n:
            break  # pragma: no cover
        out.append(unrand(cw[i], i + 1))
        i += 1
    return i, bytes(out)


def _parse(cw):
    out, i, n = bytearray(), 0, len(cw)
    while i < n:
        c = cw[i]
        i += 1
        if c == 129:
            break
        elif 1 <= c <= 128:
            out.append(c - 1)
        elif 130 <= c <= 229:
            out += b"%02d" % (c - 130)
        elif c == 230:
            i, s = _decode_text(cw, i, _C40_B, _C40_3, False)
            out += s
        elif c == 239:
            i, s = _decode_text(cw, i, _TXT_B, _TXT_3, False)
            out += s
        elif c == 238:
            i, s = _decode_text(cw, i, _X12, None, True)
            out += s
        elif c == 240:
            i, s = _decode_edifact(cw, i)
            out += s
        elif c == 231:
            i, s = _decode_base256(cw, i, n)
            out += s
        elif c == 235:
            if i < n:
                out.append((cw[i] - 1 + 128) & 0xFF)
                i += 1
        elif c == 241:  # ECI: skip its single operand
            i += 1
    return bytes(out)


def _decode(text):
    data = b(text)
    grid = _read_png(data) if data[:8] == _SIGNATURE else _read_text(text)
    w, h, nc, nr, bc, s, nb = _BY_SIZE[(len(grid), len(grid[0]))]  # size already validated by the readers
    full = []
    for bits in _positions(w, h, nc, nr, bc):
        full.append(sum((grid[y][x] & 1) << j for j, (y, x) in enumerate(bits)))
    dc_count, nec = bc - s, s // nb
    data_cw = [0] * dc_count
    for c in range(nb):
        block = full[c::nb][:dc_count // nb] + full[dc_count + c::nb][:nec]
        corrected = _rs_decode(block, nec)
        for i, v in enumerate(corrected[:dc_count // nb]):
            data_cw[c + i * nb] = v
    return _parse(data_cw)


