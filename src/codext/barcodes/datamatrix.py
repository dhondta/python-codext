# PNG and plain text rendering/reading
def _png(w, h, raw):
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    return _SIGNATURE + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0)) + \
           chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def _image(grid):
    h, w = len(grid), len(grid[0])
    return _png(w, h, b"".join(b"\x00" + bytes(0 if v else 255 for v in row) for row in grid))


def _render(grid):
    return "\n".join("".join(_DARK if v else _LIGHT for v in row) for row in grid)


def _read_png(data):
    try:
        w, h, depth, ctype = struct.unpack(">IIBB", data[16:26])
    except struct.error:
        raise DatamatrixDecodeError("'datamatrix' codec can't decode malformed PNG input")
    if (h, w) not in _BY_SIZE:
        raise DatamatrixDecodeError("'datamatrix' codec can't decode input of invalid size")
    if depth != 8 or ctype not in (0, 2):
        raise DatamatrixDecodeError("'datamatrix' codec can't decode input of unsupported PNG format")
    channels = {0: 1, 2: 3}[ctype]
    try:
        idat, pos = bytearray(), 8
        while pos < len(data):
            length, tag = struct.unpack(">I4s", data[pos:pos+8])
            if tag == b"IDAT":
                idat += data[pos+8:pos+8+length]
            elif tag == b"IEND":
                break
            pos += length + 12
        raw, pos, stride, grid = zlib.decompress(bytes(idat)), 0, w * channels, []
        for _ in range(h):
            if raw[pos] != 0:
                raise ValueError
            line = raw[pos+1:pos+1+stride]
            if len(line) < stride:
                raise ValueError
            grid.append([int(line[x*channels] < 128) for x in range(w)])
            pos += stride + 1
    except (IndexError, ValueError, struct.error, zlib.error):
        raise DatamatrixDecodeError("'datamatrix' codec can't decode malformed PNG input")
    return grid


def _read_text(text):
    lines = text.split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    if not lines or (len(lines), len(lines[0])) not in _BY_SIZE:
        raise DatamatrixDecodeError("'datamatrix' codec can't decode input of invalid size")
    n = len(lines[0])
    if any(len(line) > n for line in lines):
        raise DatamatrixDecodeError("'datamatrix' codec can't decode input of invalid size")  # pragma: no cover
    return [[int(c != _LIGHT) for c in line] + [0] * (n - len(line)) for line in lines]


# ---------------------------------------------------------------------------------------------------------------------
def datamatrix(shape=None, fmt=None):
    rect = shape == "rect"
    txt = fmt in ("text", "txt")
    def encode(text, errors="strict"):
        grid = _encode(b(text), rect)
        return (_render(grid) if txt else _image(grid)), len(text)
    def decode(text, errors="strict"):
        out = _decode(text)
        return ensure_str(out), len(out)
    return encode, decode


def datamatrix_encode(shape=None, fmt=None):
    return datamatrix(shape, fmt)[0]


def datamatrix_decode(shape=None, fmt=None):
    return datamatrix(shape, fmt)[1]


# fixtures for the decoding examples (the Base256 scheme, which the encoder does not produce, and error correction)
def _base256(data, to_end=False):
    rnd = lambda v, pos: (v + ((149 * pos) % 255) + 1) % 256
    dc = [231, rnd(0 if to_end else len(data), 2)] + [rnd(b, 3 + i) for i, b in enumerate(data)]
    return ensure_str(_image(_encode_dc(dc, False)))


def _demo_dc(dc):
    return ensure_str(_image(_encode_dc(dc, False)))


def _damaged(data, flips):
    grid = _encode(data, False)
    cells = [(y, x) for y in range(8, len(grid)) for x in range(8, len(grid[0]))]
    for y, x in cells[:flips]:
        grid[y][x] ^= 1
    return ensure_str(_image(grid))


