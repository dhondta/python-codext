_SIGNATURE = b"\x89PNG\r\n\x1a\n"
_DARK, _LIGHT = "█", " "
_GF, _PP = 256, 301  # Galois field GF(256) with primitive polynomial x^8 + x^5 + x^3 + x^2 + 1


# ---------------------------------------------------------------------------------------------------------------------
# encodation schemes (data bytes -> data codewords)
_DIGITS = range(48, 58)


def _enc_ascii(data):
    """ ASCII scheme, with digit pairing and the extended-ASCII upper shift for bytes 128-255. """
    enc, i = [], 0
    while i < len(data):
        b = data[i]
        if b in _DIGITS and i + 1 < len(data) and data[i+1] in _DIGITS:
            enc.append(130 + int(data[i:i+2]))
            i += 2
        elif b < 128:
            enc.append(b + 1)
            i += 1
        else:
            enc += [235, b - 128 + 1]
            i += 1
    return bytes(enc)


_C40_B = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
_TXT_B = " 0123456789abcdefghijklmnopqrstuvwxyz"
_SET1 = "".join(chr(i) for i in range(32))
_SET2 = "!\"#$%&'()*+,-./:;<=>?@[\\]^_"
_C40_3 = "`abcdefghijklmnopqrstuvwxyz{|}~\x7f"
_TXT_3 = "`ABCDEFGHIJKLMNOPQRSTUVWXYZ{|}~\x7f"
_X12 = "\r*> 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def _codepage(basic, set3):
    cp = {}
    for i, c in enumerate(basic):
        cp[ord(c)] = [i + 3]
    for shift, s in ((0, _SET1), (1, _SET2), (2, set3)):
        for i, c in enumerate(s):
            cp.setdefault(ord(c), [shift, i])
    return cp


_CP_C40, _CP_TXT = _codepage(_C40_B, _C40_3), _codepage(_TXT_B, _TXT_3)
_CP_X12 = {ord(c): [i] for i, c in enumerate(_X12)}


def _pack_words(raw):
    enc = []
    for i in range(0, len(raw), 3):
        word = raw[i] * 1600 + raw[i+1] * 40 + raw[i+2] + 1
        enc += [word >> 8, word & 0xFF]
    return bytes(enc)


def _tokenize(raw):
    buf = None
    for code in raw:
        if buf is not None:
            yield (buf, code)
            buf = None
        elif code >= 3:
            yield (code,)
        else:
            buf = code


def _enc_text_mode(data, codepage, magic, multiset):
    try:
        raw = []
        for b in data:
            raw += codepage[b]
    except KeyError:
        raise ValueError("incompatible character")
    lpack = (len(raw) // 3) * 3
    enc = b""
    if lpack > 0:
        enc = magic + _pack_words(raw[:lpack]) + b"\xFE"
        toascii = data[len(list(_tokenize(raw[:lpack]))):] if multiset else data[lpack:]
    else:
        toascii = data
    return enc + _enc_ascii(toascii)


def _enc_edifact(data):
    for b in data:
        if b > 127:
            raise ValueError("incompatible character")
    lpack = ((len(data) + 1) // 4) * 4
    enc = b""
    if lpack > 0:
        raw = list(data[:lpack-1]) + [0x1F]
        for b in raw:
            if not 31 <= b <= 94 and b != 0x1F:
                raise ValueError("incompatible character")
        packed = []
        for i in range(0, len(raw), 4):
            word = (raw[i] & 0x3F) << 18 | (raw[i+1] & 0x3F) << 12 | (raw[i+2] & 0x3F) << 6 | (raw[i+3] & 0x3F)
            packed += [word >> 16, (word >> 8) & 0xFF, word & 0xFF]
        enc = b"\xF0" + bytes(packed)
    remaining = min(len(data), len(data) + 1 - lpack)
    return enc + _enc_ascii(data[len(data) - remaining:])


def _encode_data(data):
    """ Encode the data bytes with the most compact scheme. """
    candidates = [_enc_ascii(data)]
    for cp, magic, multi in ((_CP_C40, b"\xE6", True), (_CP_TXT, b"\xEF", True), (_CP_X12, b"\xEE", False)):
        try:
            candidates.append(_enc_text_mode(data, cp, magic, multi))
        except ValueError:
            pass
    try:
        candidates.append(_enc_edifact(data))
    except ValueError:
        pass
    return min(candidates, key=len)


