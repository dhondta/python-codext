# -*- coding: UTF-8 -*-
"""Data Matrix Codec - Data Matrix (ECC200) content encoding.

This encodes the input as a real (standard, scannable) Data Matrix barcode (ISO/IEC 16022, ECC200), a 2D matrix barcode
 with an "L"-shaped solid finder pattern and a dashed timing pattern on the two other sides. It encodes the data with
 the most compact of the ASCII (with the digit-pair and extended-ASCII optimizations), C40, Text, X12 and EDIFACT
 schemes, selects the smallest symbol (square from 10x10 to 144x144, or rectangular with the "-rect" variant) that fits
 and adds the Reed-Solomon error correction. Decoding reads the symbol back and applies Reed-Solomon error correction,
 so that a damaged code can still be decoded ; it handles every encodation scheme (including Base256), so that Data
 Matrix codes generated by other tools can be read.

By default, the Data Matrix is a grayscale PNG image (one pixel per module), but the "-text" variant (e.g.
 "datamatrix-text" or "datamatrix-rect-text") renders it as plain text instead, with a full block for a dark module and
 a space for a light one. Decoding accepts either form, auto-detecting the image from its PNG signature.

This codec:
- en/decodes strings from str to str
- en/decodes strings from bytes to bytes
- decodes file content to str (read)
- encodes file content from str to bytes (write)

Reference: https://en.wikipedia.org/wiki/Data_Matrix (ISO/IEC 16022, ECC200 ; encoder ported from datamatrix-svg)
"""
