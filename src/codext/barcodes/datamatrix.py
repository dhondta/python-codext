# Reed-Solomon decoding (GF(256), first consecutive root alpha^1) -- shared formulation with the other barcodes
def _gf_tables():
    exp, log, x = [0] * 512, [0] * 256, 1
    for i in range(255):
        exp[i], log[x] = x, i
        x <<= 1
        if x >= 256:
            x ^= _PP
    for i in range(255, 512):
        exp[i] = exp[i - 255]
    return exp, log


_EXP, _LOG = _gf_tables()


def _mul(a, b):
    return 0 if a == 0 or b == 0 else _EXP[_LOG[a] + _LOG[b]]


def _rs_decode(msg, nec):
    msg = list(msg)
    synd = [0] + [0] * nec
    for k in range(nec):
        y = 0
        for coef in msg:
            y = _mul(y, _EXP[k + 1]) ^ coef
        synd[k+1] = y
    if max(synd) == 0:
        return msg
    err_loc, old_loc = [1], [1]
    for i in range(nec):
        delta = synd[i+1]
        for j in range(1, len(err_loc)):
            delta ^= _mul(err_loc[-(j+1)], synd[i+1-j])
        old_loc = old_loc + [0]
        if delta != 0:
            if len(old_loc) > len(err_loc):
                new_loc = [_mul(c, delta) for c in old_loc]
                old_loc = [_mul(c, _EXP[255 - _LOG[delta]]) for c in err_loc]
                err_loc = new_loc
            err_loc = _poly_add(err_loc, [_mul(c, delta) for c in old_loc])
    while err_loc and err_loc[0] == 0:
        err_loc.pop(0)  # pragma: no cover
    errs = len(err_loc) - 1
    if errs * 2 > nec:
        raise DatamatrixDecodeError("'datamatrix' codec can't decode too damaged input")  # pragma: no cover
    rev = err_loc[::-1]
    err_pos = [len(msg) - 1 - i for i in range(len(msg)) if _poly_eval(rev, _EXP[i]) == 0]
    if len(err_pos) != errs:
        raise DatamatrixDecodeError("'datamatrix' codec can't decode too damaged input")
    coef_pos = [len(msg) - 1 - p for p in err_pos]
    e_loc = [1]
    for i in coef_pos:
        e_loc = _poly_mul(e_loc, _poly_add([1], [_EXP[i], 0]))
    prod = _poly_mul(synd[::-1], e_loc)
    remainder = prod[len(prod) - len(e_loc):]
    xs = [_EXP[(-(255 - p)) % 255] for p in coef_pos]
    for i, xi in enumerate(xs):
        xi_inv, denom = _EXP[255 - _LOG[xi]], 1
        for j in range(len(xs)):
            if j != i:
                denom = _mul(denom, 1 ^ _mul(xi_inv, xs[j]))
        num = _poly_eval(remainder, xi_inv)
        msg[err_pos[i]] ^= (0 if num == 0 else _mul(num, _EXP[255 - _LOG[denom]]))
    for k in range(nec):
        y = 0
        for coef in msg:
            y = _mul(y, _EXP[k + 1]) ^ coef
        if y != 0:  # pragma: no cover
            raise DatamatrixDecodeError("'datamatrix' codec can't decode too damaged input")
    return msg


def _poly_add(p, q):
    r = [0] * max(len(p), len(q))
    for i in range(len(p)):
        r[i + len(r) - len(p)] = p[i]
    for i in range(len(q)):
        r[i + len(r) - len(q)] ^= q[i]
    return r


def _poly_mul(p, q):
    r = [0] * (len(p) + len(q) - 1)
    for i in range(len(p)):
        for j in range(len(q)):
            r[i+j] ^= _mul(p[i], q[j])
    return r


def _poly_eval(p, x):
    y = p[0]
    for coef in p[1:]:
        y = _mul(y, x) ^ coef
    return y


