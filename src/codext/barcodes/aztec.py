def _choose(bits, ec_percent):
    for (size, compact), (layers, codewords, cw_bits) in _CONFIGS.items():
        data_cw = len(_data_codewords(bits, cw_bits))
        if compact and data_cw > 64:  # the compact mode message stores the count on 6 bits (at most 64 codewords)
            continue
        if (data_cw + 3) * 100.0 / (100 - ec_percent) < codewords:
            return size, compact, layers, codewords, cw_bits, data_cw
    raise ValueError("'aztec' codec can't encode input of more than %d bytes" % _max_bytes(ec_percent))


def _max_bytes(ec_percent):
    size, compact = 151, False
    layers, codewords, cw_bits = _CONFIGS[(size, compact)]
    return int((codewords * (100 - ec_percent) / 100.0 - 3) * cw_bits) // 8


def _encode_bits(bits, ec_percent):
    size, compact, layers, codewords, cw_bits, data_cw = _choose(bits, ec_percent)
    cw = _rs_encode((_data_codewords(bits, cw_bits) + [0] * (codewords - data_cw))[:codewords], data_cw,
                    codewords - data_cw, 2 ** cw_bits, _POLY[cw_bits])
    grid = _blank(size)
    _patterns(grid, size, compact)
    for (y, x), bit in zip(_mode_positions(size, compact), _mode_message(compact, layers, data_cw)):
        grid[y][x] = int(bit)
    full = "".join(_bits(c, cw_bits) for c in cw)[::-1]
    for (y, x), bit in zip(_data_positions(size, compact, layers, codewords * cw_bits), full):
        grid[y][x] = int(bit)
    return grid


def _encode(data, ec_percent):
    return _encode_bits(_seq_to_bits(_optimal_sequence(data)), ec_percent)


# ---------------------------------------------------------------------------------------------------------------------
# decoding
def _parse(bits):
    """ Decode the data bit string (all compaction modes) into the original bytes. """
    out, mode, prev, shift, i, n = bytearray(), _U, _U, False, 0, len(bits)
    while i + _CSIZE[mode] <= n:
        index = int(bits[i:i+_CSIZE[mode]], 2)
        i += _CSIZE[mode]
        ch = _CHARS[mode][index]
        if isinstance(ch, int):
            out.append(ch)
        elif isinstance(ch, bytes):
            out += ch
        if shift:
            mode, shift = prev, False
        if isinstance(ch, tuple) and ch[0] == 'L':
            mode = ch[1]
        elif ch == 'FLG':
            if i + 3 > n:
                break  # pragma: no cover
            flg = int(bits[i:i+3], 2)
            i += 3 + 4 * flg
        elif ch == ('S', _B):
            if i + 5 > n:
                break
            blen = int(bits[i:i+5], 2)
            i += 5
            if blen == 0:
                if i + 11 > n:
                    break  # pragma: no cover
                blen = int(bits[i:i+11], 2) + 31
                i += 11
            for _ in range(blen):
                if i + 8 > n:
                    break  # pragma: no cover
                out.append(int(bits[i:i+8], 2))
                i += 8
        elif isinstance(ch, tuple) and ch[0] == 'S':
            mode, prev, shift = ch[1], mode, True
    return bytes(out)


def _read_mode(grid, size, compact):
    positions = _mode_positions(size, compact)
    bits = "".join(str(grid[y][x]) for y, x in positions)
    total = 7 if compact else 10
    init = 2 if compact else 4
    cw = [int(bits[i:i+4], 2) for i in range(0, total * 4, 4)]
    cw = _rs_decode(cw, total - init, 16, _POLY[4])[:init]
    word = "".join(_bits(v, 4) for v in cw)
    if compact:
        return int(word[:2], 2) + 1, int(word[2:8], 2) + 1
    return int(word[:5], 2) + 1, int(word[5:16], 2) + 1


def _decode(text):
    data = b(text)
    grid = _read_png(data) if data[:8] == _SIGNATURE else _read_text(text)
    size = len(grid)
    candidates = [(size, compact) for compact in (True, False) if (size, compact) in _CONFIGS]
    for si, (sz, compact) in enumerate(candidates):
        cfg_layers, codewords, cw_bits = _CONFIGS[(sz, compact)]
        try:
            layers, data_cw = _read_mode(grid, sz, compact)
            if layers != cfg_layers or not 1 <= data_cw <= codewords:
                raise AztecDecodeError("bad mode message")
        except (AztecDecodeError, ValueError):
            if si == len(candidates) - 1:
                raise AztecDecodeError("'aztec' codec can't decode input with corrupted mode message")
            continue
        read = "".join(str(grid[y][x]) for y, x in _data_positions(sz, compact, layers, codewords * cw_bits))
        full = read[::-1]
        cw = [int(full[i:i+cw_bits], 2) for i in range(0, codewords * cw_bits, cw_bits)]
        cw = _rs_decode(cw, codewords - data_cw, 2 ** cw_bits, _POLY[cw_bits])[:data_cw]
        return _parse(_destuff(cw, cw_bits))


