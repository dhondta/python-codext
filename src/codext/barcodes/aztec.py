# Reed-Solomon encoding (in place) and generic Galois field helpers
def _rs_encode(wd, nd, nc, gf, pp):
    """ Append nc Reed-Solomon check codewords to the nd data codewords in wd (GF(gf), modulus pp). """
    log, alog = {0: 1 - gf}, {0: 1}
    for i in range(1, gf):
        alog[i] = alog[i-1] * 2
        if alog[i] >= gf:
            alog[i] ^= pp
        log[alog[i]] = i
    prod = lambda x, y: 0 if not x or not y else alog[(log[x] + log[y]) % (gf - 1)]
    c = {0: 1}
    for i in range(1, nc + 1):
        c[i] = 0
    for i in range(1, nc + 1):
        c[i] = c[i-1]
        for j in range(i - 1, 0, -1):
            c[j] = c[j-1] ^ prod(c[j], alog[i])
        c[0] = prod(c[0], alog[i])
    for i in range(nd, nd + nc):
        wd[i] = 0
    for i in range(nd):
        k = wd[nd] ^ wd[i]
        for j in range(nc):
            wd[nd + j] = prod(k, c[nc - j - 1])
            if j < nc - 1:
                wd[nd + j] ^= wd[nd + j + 1]
    return wd


def _gf_tables(gf, pp):
    exp, log, x = [0] * (2 * gf), [0] * gf, 1
    for i in range(gf - 1):
        exp[i], log[x] = x, i
        x <<= 1
        if x >= gf:
            x ^= pp
    for i in range(gf - 1, 2 * gf):
        exp[i] = exp[i - (gf - 1)]
    return exp, log


def _rs_decode(msg, nec, gf, pp):
    """ Correct the errors of a Reed-Solomon codeword (GF(gf), first consecutive root alpha^1) and return it. """
    exp, log, fc = *_gf_tables(gf, pp), gf - 1
    mul = lambda a, b: 0 if a == 0 or b == 0 else exp[log[a] + log[b]]
    inv = lambda a: exp[fc - log[a]]
    def ev(p, x):
        y = p[0]
        for coef in p[1:]:
            y = mul(y, x) ^ coef
        return y
    def padd(p, q):
        r = [0] * max(len(p), len(q))
        for i in range(len(p)):
            r[i + len(r) - len(p)] = p[i]
        for i in range(len(q)):
            r[i + len(r) - len(q)] ^= q[i]
        return r
    def pmul(p, q):
        r = [0] * (len(p) + len(q) - 1)
        for i in range(len(p)):
            for j in range(len(q)):
                r[i+j] ^= mul(p[i], q[j])
        return r
    msg, synd = list(msg), [0] + [0] * nec
    for k in range(nec):
        synd[k+1] = ev(msg, exp[k + 1])
    if max(synd) == 0:
        return msg
    err_loc, old_loc = [1], [1]
    for i in range(nec):
        delta = synd[i+1]
        for j in range(1, len(err_loc)):
            delta ^= mul(err_loc[-(j+1)], synd[i+1-j])
        old_loc = old_loc + [0]
        if delta != 0:
            if len(old_loc) > len(err_loc):
                new_loc = [mul(c, delta) for c in old_loc]
                old_loc = [mul(c, inv(delta)) for c in err_loc]
                err_loc = new_loc
            err_loc = padd(err_loc, [mul(c, delta) for c in old_loc])
    while err_loc and err_loc[0] == 0:
        err_loc.pop(0)  # pragma: no cover
    errs = len(err_loc) - 1
    if errs * 2 > nec:
        raise AztecDecodeError("'aztec' codec can't decode too damaged input")  # pragma: no cover
    rev = err_loc[::-1]
    err_pos = [len(msg) - 1 - i for i in range(len(msg)) if ev(rev, exp[i]) == 0]
    if len(err_pos) != errs:
        raise AztecDecodeError("'aztec' codec can't decode too damaged input")
    coef_pos = [len(msg) - 1 - p for p in err_pos]
    e_loc = [1]
    for i in coef_pos:
        e_loc = pmul(e_loc, padd([1], [exp[i], 0]))
    prod = pmul(synd[::-1], e_loc)
    remainder = prod[len(prod) - len(e_loc):]
    xs = [exp[(-(fc - p)) % fc] for p in coef_pos]
    for i, xi in enumerate(xs):
        xi_inv, denom = inv(xi), 1
        for j in range(len(xs)):
            if j != i:
                denom = mul(denom, 1 ^ mul(xi_inv, xs[j]))
        msg[err_pos[i]] ^= _gf_div(ev(remainder, xi_inv), denom, mul, inv)  # fcr=1: no X^(1-fcr) factor
    for k in range(nec):
        if ev(msg, exp[k + 1]) != 0:  # pragma: no cover
            raise AztecDecodeError("'aztec' codec can't decode too damaged input")
    return msg


def _gf_div(a, b, mul, inv):
    return 0 if a == 0 else mul(a, inv(b))


