"""Aztec Code Codec - Aztec code content encoding.

This encodes the input as a real (standard, scannable) Aztec code (ISO/IEC 24778), a 2D matrix barcode with a central
 bulls-eye finder pattern and the data spiralling around it. It uses the optimal high-level compaction (upper, lower,
 mixed, punctuation and digit modes plus binary shift, with the smallest possible mode switching), selects the smallest
 symbol (compact 1 to 4 layers, then full 1 to 32 layers) that fits the data for the chosen error correction percentage
 (given in the codec name, e.g. "aztec-33" ; 23% by default) and adds the Reed-Solomon error correction over the proper
 Galois field. Decoding reads the symbol back, recovering its size, layer count and error correction from the mode
 message, applying Reed-Solomon error correction so that a damaged code can still be decoded ; it handles all the
 compaction modes, so that Aztec codes generated by other tools can be read.

By default, the Aztec code is a grayscale PNG image (one pixel per module), but the "-text" variant (e.g. "aztec-text"
 or "aztec-33-text") renders it as plain text instead, with a full block for a dark module and a space for a light one.
 Decoding accepts either form, auto-detecting the image from its PNG signature.

This codec:
- en/decodes strings from str to str
- en/decodes strings from bytes to bytes
- decodes file content to str (read)
- encodes file content from str to bytes (write)

Reference: https://en.wikipedia.org/wiki/Aztec_Code (ISO/IEC 24778)
"""
