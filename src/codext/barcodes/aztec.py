# high-level compaction: data -> optimal mode sequence -> bits -> codewords
def _optimal_sequence(data):
    """ Find the sequence of tokens encoding data with the minimum number of bits. """
    back_to = {m: _U for m in range(6)}
    cur_len = {m: 0 if m == _U else _E for m in range(6)}
    cur_seq = {m: [] for m in range(6)}
    prev_c = None
    for c in data:
        for x in range(6):
            for y in range(6):
                if cur_len[x] + _LATCH[x][y] < cur_len[y]:
                    cur_len[y] = cur_len[x] + _LATCH[x][y]
                    cur_seq[y] = cur_seq[x][:]
                    back_to[y] = y
                    if y == _B:
                        if x in (_P, _D):
                            back_to[y] = _U
                            cur_seq[y] += [('L', _U), ('S', _B), 'SIZE']
                        else:
                            back_to[y] = x
                            cur_seq[y] += [('S', _B), 'SIZE']
                    elif cur_seq[x]:
                        if x == _D and y == _P:
                            cur_seq[y] += ['RESUME', ('L', _U), ('L', _MX), ('L', _P)]
                        elif x in (_P, _D) and y != _U:
                            cur_seq[y] += ['RESUME', ('L', _U), ('L', y)]
                        elif x == _L and y == _U:
                            cur_seq[y] += [('L', _D), ('L', _U)]
                        elif x in (_U, _L) and y == _P:
                            cur_seq[y] += [('L', _MX), ('L', y)]
                        elif x == _MX and y != _U:
                            if y == _P:
                                cur_seq[y] += [('L', _P)]
                                back_to[y] = _P
                            else:
                                cur_seq[y] += [('L', _U), ('L', _D)]
                                back_to[y] = _D
                            continue
                        elif x == _B:
                            if y == back_to[x]:
                                cur_seq[y] += ['RESUME']
                            elif y == _U:
                                if back_to[x] == _L:
                                    cur_seq[y] += ['RESUME', ('L', _D), ('L', _U)]
                                if back_to[x] == _MX:
                                    cur_seq[y] += ['RESUME', ('L', _U)]
                            elif y == _L:
                                cur_seq[y] += ['RESUME', ('L', _L)]
                            elif y == _MX:
                                cur_seq[y] += ['RESUME', ('L', _MX)]
                            elif y == _P:
                                if back_to[x] == _MX:
                                    cur_seq[y] += ['RESUME', ('L', _P)]
                                else:
                                    cur_seq[y] += ['RESUME', ('L', _MX), ('L', _P)]
                            elif y == _D:
                                if back_to[x] == _MX:
                                    cur_seq[y] += ['RESUME', ('L', _U), ('L', _D)]
                                else:
                                    cur_seq[y] += ['RESUME', ('L', _D)]
                        else:
                            cur_seq[y] += ['RESUME', ('L', y)]
                    else:  # this branch is only ever reached for the first character, hence from the upper mode
                        if x in (_P, _D):
                            cur_seq[y] = [('L', _U), ('L', y)]  # pragma: no cover
                        elif x == _L and y == _U:
                            cur_seq[y] = [('L', _D), ('L', _U)]  # pragma: no cover
                        elif x in (_B, _U, _L) and y == _P:
                            cur_seq[y] = [('L', _MX), ('L', y)]
                        else:
                            cur_seq[y] = [('L', y)]
        next_len = {m: _E for m in range(6)}
        next_seq = {m: [] for m in range(6)}
        possible_modes = [m for m in range(6) if m == _B or c in _CHARS[m]]
        for x in possible_modes:
            if back_to[x] == _D and x == _L:
                cur_seq[x] += [('L', _U), ('L', _L)]
                cur_len[x] += _LATCH[back_to[x]][x]
                back_to[x] = _L
            if cur_len[x] + _CSIZE[x] < next_len[x]:
                next_len[x] = cur_len[x] + _CSIZE[x]
                next_seq[x] = cur_seq[x] + [c]
            for y in range(6):
                if (y, x) in _SHIFT and cur_len[y] + _SHIFT[(y, x)] + _CSIZE[x] < next_len[y]:
                    next_len[y] = cur_len[y] + _SHIFT[(y, x)] + _CSIZE[x]
                    next_seq[y] = cur_seq[y] + [('S', x), c]
        if prev_c and bytes((prev_c, c)) in _PUNCT2:
            for x in range(6):
                last_c = cur_seq[x][-1] if cur_seq[x] else None
                # the last char is in punct mode only if directly shifted to punct, else via the active punct latch
                prev_tok = cur_seq[x][-2] if len(cur_seq[x]) >= 2 else None
                if isinstance(prev_tok, tuple) and prev_tok[0] == 'S':
                    last_mode = prev_tok[1]
                else:
                    last_mode = next((s[1] for s in reversed(cur_seq[x][:-1]) if isinstance(s, tuple)
                                      and s[0] == 'L'), _U)
                if last_mode == _P and isinstance(last_c, int) and bytes((last_c, c)) in _PUNCT2 and x != _MX:
                    if cur_len[x] < next_len[x]:
                        next_len[x] = cur_len[x]
                        next_seq[x] = cur_seq[x][:-1] + [bytes((last_c, c))]
        if len(next_seq[_B]) - 2 == 32:
            next_len[_B] += 11
        cur_len, cur_seq, prev_c = next_len.copy(), next_seq.copy(), c
    result_seq = cur_seq[sorted(cur_len, key=cur_len.__getitem__)[0]]
    # resolve the binary run sizes
    sizes, rlen, reset_pos = {}, len(result_seq), len(result_seq) - 1
    for i, c in enumerate(reversed(result_seq)):
        if c == 'SIZE':
            sizes[i] = reset_pos - (rlen - i - 1)
            reset_pos = rlen - i
        elif c == 'RESUME':
            reset_pos = rlen - i - 2
    for size_pos in sizes:
        result_seq[len(result_seq) - size_pos - 1] = sizes[size_pos]
    result_seq = [x for x in result_seq if x != 'RESUME']
    out, is_len = [], False
    for c in result_seq:
        if is_len:
            if c > 31:
                out += [0, c - 31]
            else:
                out.append(c)
            is_len = False
        else:
            out.append(c)
        if c == ('S', _B):
            is_len = True
    return out


def _bits(value, length):
    return bin(value)[2:].zfill(length)


def _seq_to_bits(seq):
    """ Convert the optimal token sequence to its data bit string. """
    out, mode, prev, shift, seq, i = "", _U, _U, False, list(seq), 0
    while i < len(seq):
        ch = seq[i]
        i += 1
        out += _bits(_CHARS[mode].index(ch), _CSIZE[mode])
        if shift:
            mode, shift = prev, False
        if isinstance(ch, tuple) and ch[0] == 'L':
            mode = ch[1]
        elif ch == ('S', _B):
            seq_len = seq[i]
            i += 1
            out += _bits(seq_len, 5)
            if seq_len == 0:
                seq_len = seq[i] + 31
                out += _bits(seq[i], 11)
                i += 1
            for _ in range(seq_len):
                out += _bits(seq[i], 8)
                i += 1
        elif isinstance(ch, tuple) and ch[0] == 'S':
            mode, prev, shift = ch[1], mode, True
    return out


def _data_codewords(bits, cw_bits):
    """ Split the data bits into codewords, stuffing/padding to avoid all-zero and all-ones codewords. """
    if not bits:  # empty input: a single all-padding codeword, so that the symbol still holds one data codeword
        return [int('1' * (cw_bits - 1) + '0', 2)]
    codewords, sub = [], ""
    for bit in bits:
        sub += bit
        if len(sub) == cw_bits - 1 and sub.find('1') < 0:
            sub += '1'
        if len(sub) == cw_bits - 1 and sub.find('0') < 0:
            sub += '0'
        if len(sub) >= cw_bits:
            codewords.append(int(sub, 2))
            sub = ""
    if sub:
        sub = sub.ljust(cw_bits, '1')
        if sub.find('0') < 0:
            sub = sub[:-1] + '0'
        codewords.append(int(sub, 2))
    return codewords


def _destuff(codewords, cw_bits):
    """ Inverse of the bit stuffing: rebuild the data bit string from the data codewords. """
    out = ""
    for cw in codewords:
        b = _bits(cw, cw_bits)
        if b[:cw_bits-1] == '0' * (cw_bits - 1) or b[:cw_bits-1] == '1' * (cw_bits - 1):
            out += b[:cw_bits-1]
        else:
            out += b
    return out


