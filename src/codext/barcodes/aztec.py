# matrix geometry (finder, orientation, reference grid, mode message and data placement)
def _blank(size):
    return [[0] * size for _ in range(size)]


def _patterns(grid, size, compact):
    """ Draw the bulls-eye finder, the orientation marks and (for full symbols) the reference grid. """
    c, r = size // 2, 5 if compact else 7
    for x in range(-r, r):
        for y in range(-r, r):
            grid[c+y][c+x] = (max(abs(x), abs(y)) + 1) % 2
    grid[c-r][c-r] = grid[c-r+1][c-r] = grid[c-r][c-r+1] = 1
    grid[c-r][c+r] = grid[c-r+1][c+r] = grid[c+r-1][c+r] = 1
    if not compact:
        for x in range(-c, c + 1):
            for y in range(-c, c + 1):
                if -r <= x <= r and -r <= y <= r:
                    continue
                if x % 16 == 0 or y % 16 == 0:
                    grid[c+y][c+x] = (x + y + 1) % 2


def _mode_positions(size, compact):
    """ The (row, column) coordinates of the mode message bits, in order. """
    c, r, side = size // 2, 5 if compact else 7, 7 if compact else 11
    count, positions, index = (7 if compact else 10) * 4, [], 0
    while len(positions) < count:
        if not compact and index % side == 5:
            index += 1
        if index < side:
            x, y = index + 2 - r, -r
        elif index < side * 2:
            x, y = r, index % side + 2 - r
        elif index < side * 3:
            x, y = r - index % side - 2, r
        else:
            x, y = -r, r - index % side - 2
        positions.append((c + y, c + x))
        index += 1
    return positions


def _mode_message(compact, layers, data_cw):
    if compact:
        word, total = _bits(layers - 1, 2) + _bits(data_cw - 1, 6), 7
    else:
        word, total = _bits(layers - 1, 5) + _bits(data_cw - 1, 11), 10
    init = [int(word[i:i+4], 2) for i in range(0, len(word), 4)]
    cw = _rs_encode((init + [0] * (total - len(init)))[:total], len(init), total - len(init), 16, _POLY[4])
    return "".join(_bits(v, 4) for v in cw)


def _data_positions(size, compact, layers, nbits):
    """ The (row, column) coordinates of the data bits, in the spiral order they are written/read. """
    c, r = size // 2, 5 if compact else 7
    num, side, layer_index = 2, "top", 0
    pos_x, pos_y, positions = c - r, c - r - 1, []
    for _ in range(0, nbits, 2):
        num += 1
        max_num = r * 2 + layer_index * 4 + (4 if compact else 3)
        if side == "top":
            dy0 = 1 if not compact and (c - pos_y) % 16 == 0 else 0
            dy1 = 2 if not compact and (c - pos_y + 1) % 16 == 0 else 1
            positions += [(pos_y - dy0, pos_x), (pos_y - dy1, pos_x)]
            pos_x += 1
            if num > max_num:
                num, side, pos_x, pos_y = 2, "right", pos_x - 1, pos_y + 1
            if not compact and (c - pos_x) % 16 == 0:
                pos_x += 1
            if not compact and (c - pos_y) % 16 == 0:
                pos_y += 1
        elif side == "right":
            dx0 = 1 if not compact and (c - pos_x) % 16 == 0 else 0
            dx1 = 2 if not compact and (c - pos_x + 1) % 16 == 0 else 1
            positions += [(pos_y, pos_x - dx1), (pos_y, pos_x - dx0)]
            pos_y += 1
            if num > max_num:
                num, side, pos_x, pos_y = 2, "bottom", pos_x - 2, pos_y - 1
                if not compact and (c - pos_x - 1) % 16 == 0:
                    pos_x -= 1
            if not compact and (c - pos_y) % 16 == 0:
                pos_y += 1
            if not compact and (c - pos_x) % 16 == 0:
                pos_x -= 1
        elif side == "bottom":
            dy0 = 1 if not compact and (c - pos_y) % 16 == 0 else 0
            dy1 = 2 if not compact and (c - pos_y + 1) % 16 == 0 else 1
            positions += [(pos_y - dy1, pos_x), (pos_y - dy0, pos_x)]
            pos_x -= 1
            if num > max_num:
                num, side, pos_x, pos_y = 2, "left", pos_x + 1, pos_y - 2
                if not compact and (c - pos_y - 1) % 16 == 0:
                    pos_y -= 1
            if not compact and (c - pos_x) % 16 == 0:
                pos_x -= 1
            if not compact and (c - pos_y) % 16 == 0:
                pos_y -= 1
        else:  # left
            dx0 = 1 if not compact and (c - pos_x) % 16 == 0 else 0
            dx1 = 2 if not compact and (c - pos_x - 1) % 16 == 0 else 1
            positions += [(pos_y, pos_x + dx1), (pos_y, pos_x + dx0)]
            pos_y -= 1
            if num > max_num:
                num, side, layer_index = 2, "top", layer_index + 1
            if not compact and (c - pos_y) % 16 == 0:
                pos_y -= 1
    return positions


