# PNG and plain text rendering/reading
def _png(n, raw):
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    return _SIGNATURE + chunk(b"IHDR", struct.pack(">IIBBBBB", n, n, 8, 0, 0, 0, 0)) + \
           chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def _image(grid):
    return _png(len(grid), b"".join(b"\x00" + bytes(0 if v else 255 for v in row) for row in grid))


def _render(grid):
    return "\n".join("".join(_DARK if v else _LIGHT for v in row) for row in grid)


def _read_png(data):
    try:
        w, h, depth, ctype = struct.unpack(">IIBB", data[16:26])
    except struct.error:
        raise AztecDecodeError("'aztec' codec can't decode malformed PNG input")
    if w != h or w not in _SIZES:
        raise AztecDecodeError("'aztec' codec can't decode input of invalid size")
    if depth != 8 or ctype not in (0, 2):
        raise AztecDecodeError("'aztec' codec can't decode input of unsupported PNG format")
    channels = {0: 1, 2: 3}[ctype]
    try:
        idat, pos = bytearray(), 8
        while pos < len(data):
            length, tag = struct.unpack(">I4s", data[pos:pos+8])
            if tag == b"IDAT":
                idat += data[pos+8:pos+8+length]
            elif tag == b"IEND":
                break
            pos += length + 12
        raw, pos, stride, grid = zlib.decompress(bytes(idat)), 0, w * channels, []
        for _ in range(h):
            if raw[pos] != 0:
                raise ValueError
            line = raw[pos+1:pos+1+stride]
            if len(line) < stride:
                raise ValueError
            grid.append([int(line[x*channels] < 128) for x in range(w)])
            pos += stride + 1
    except (IndexError, ValueError, struct.error, zlib.error):
        raise AztecDecodeError("'aztec' codec can't decode malformed PNG input")
    return grid


def _read_text(text):
    lines = text.split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    n = len(lines[0]) if lines else 0
    if n not in _SIZES or len(lines) != n or any(len(line) > n for line in lines):
        raise AztecDecodeError("'aztec' codec can't decode input of invalid size")
    return [[int(c != _LIGHT) for c in line] + [0] * (n - len(line)) for line in lines]


# ---------------------------------------------------------------------------------------------------------------------
def aztec(ec=None, fmt=None):
    ec_percent = int(ec) if ec not in (None, "") else 23
    txt = fmt in ("text", "txt")
    def encode(text, errors="strict"):
        grid = _encode(b(text), ec_percent)
        return (_render(grid) if txt else _image(grid)), len(text)
    def decode(text, errors="strict"):
        out = _decode(text)
        return ensure_str(out), len(out)
    return encode, decode


def aztec_encode(ec=None, fmt=None):
    return aztec(ec, fmt)[0]


def aztec_decode(ec=None, fmt=None):
    return aztec(ec, fmt)[1]


# fixtures for the decoding examples (error correction, the FLG designator and malformed inputs, which the encoder
#  above does not produce on its own)
def _damaged(data, ec, flips):
    grid = _encode(data, ec)
    n, c = len(grid), len(grid) // 2
    r = 5 if (n, True) in _CONFIGS and _CONFIGS.get((n, True), (0,))[0] else 7
    cells = [(y, x) for y in range(n) for x in range(n) if max(abs(x - c), abs(y - c)) > 7]
    for y, x in cells[:flips]:
        grid[y][x] ^= 1
    return ensure_str(_image(grid))


def _flg_demo():
    # a symbol whose data holds a FLG(0) (FNC1) designator followed by "OK", exercising the FLG decoding branch
    bits = "00000" + "00000" + "000" + _bits(_CHARS[_U].index(ord("O")), 5) + _bits(_CHARS[_U].index(ord("K")), 5)
    return ensure_str(_image(_encode_bits(bits, 23)))


