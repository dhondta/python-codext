# QR code decoding
def _read_format(grid):
    """ Recover the error correction level and the mask from the format information. """
    n, raw = len(grid), 0
    for i in range(15):
        raw |= grid[i if i < 6 else i + 1 if i < 8 else n - 15 + i][8] << i
    best, data5 = 16, 0
    for d in range(32):
        dist = bin(raw ^ _bch_format(d)).count("1")
        if dist < best:
            best, data5 = dist, d
    if best > 3:
        raise QrDecodeError("'qr' codec can't decode input with corrupted format information")
    return _FORMAT_EC[data5 >> 3], data5 & 7


def _function_map(version):
    """ Boolean grid telling which modules are function patterns (hence not data modules). """
    m = _blank(version)
    _type_info(m, 'M', 0, True)
    if version >= 7:
        _type_number(m, version, True)
    return [[c is not None for c in row] for row in m]


def _deinterleave(cw, version, level):
    """ Rebuild the per-block data codewords from the interleaved stream, applying error correction. """
    blocks = _blocks(version, level)
    dc_counts, ec_counts = [d for _, d in blocks], [t - d for t, d in blocks]
    dcdata, ecdata, idx = [[] for _ in blocks], [[] for _ in blocks], 0
    for i in range(max(dc_counts)):
        for b in range(len(blocks)):
            if i < dc_counts[b]:
                dcdata[b].append(cw[idx])
                idx += 1
    for i in range(max(ec_counts)):
        for b in range(len(blocks)):
            if i < ec_counts[b]:
                ecdata[b].append(cw[idx])
                idx += 1
    data = []
    for b in range(len(blocks)):
        corrected = _rs_decode(dcdata[b] + ecdata[b], ec_counts[b])
        data += corrected[:dc_counts[b]]
    return data


_ALPHANUM = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:"


def _parse(codewords, version):
    """ Parse the data codewords (byte, numeric or alphanumeric modes) and return the original bytes. """
    bits = [(cw >> (7 - i)) & 1 for cw in codewords for i in range(8)]
    pos, out = 0, bytearray()

    def read(k):
        nonlocal pos
        v = 0
        for _ in range(k):
            v = (v << 1) | bits[pos]
            pos += 1
        return v

    while pos + 4 <= len(bits):
        mode = read(4)
        if mode == 0:                                                           # terminator
            break
        elif mode == 0b0100:                                                    # byte
            for _ in range(read(8 if version < 10 else 16)):
                out.append(read(8))
        elif mode == 0b0001:                                                    # numeric
            count, i = read(10 if version < 10 else 12 if version < 27 else 14), 0
            while i < count:
                g = min(3, count - i)
                out += str(read({1: 4, 2: 7, 3: 10}[g])).zfill(g).encode()
                i += g
        elif mode == 0b0010:                                                    # alphanumeric
            count, i = read(9 if version < 10 else 11 if version < 27 else 13), 0
            while i < count:
                if count - i >= 2:
                    v = read(11)
                    out.append(ord(_ALPHANUM[v // 45]))
                    out.append(ord(_ALPHANUM[v % 45]))
                    i += 2
                else:
                    out.append(ord(_ALPHANUM[read(6)]))
                    i += 1
        else:
            raise QrDecodeError("'qr' codec can't decode unsupported mode")
    return bytes(out)


def _decode(text):
    data = b(text)
    grid = _read_png(data) if data[:8] == _SIGNATURE else _read_text(text)
    n, version = len(grid), (len(grid) - 17) // 4
    level, mask = _read_format(grid)
    func, mf = _function_map(version), _MASKS[mask]
    bits = []
    for row, col in _traverse(n):
        if not func[row][col]:
            bits.append(grid[row][col] ^ 1 if mf(row, col) else grid[row][col])
    cw = [int("".join(map(str, bits[i:i+8])), 2) for i in range(0, len(bits) // 8 * 8, 8)]
    return _parse(_deinterleave(cw, version, level), version)


# ---------------------------------------------------------------------------------------------------------------------
def qr(level=None, fmt=None):
    lvl = (level or "M").upper()
    txt = fmt in ("text", "txt")
    def encode(text, errors="strict"):
        grid = _encode(b(text), lvl)
        return (_render(grid) if txt else _image(grid)), len(text)
    def decode(text, errors="strict"):
        out = _decode(text)
        return ensure_str(out), len(out)
    return encode, decode


def qr_encode(level=None, fmt=None):
    return qr(level, fmt)[0]


def qr_decode(level=None, fmt=None):
    return qr(level, fmt)[1]


# fixtures building the decoding examples below: the numeric and alphanumeric modes and the error correction are not
#  exercised by the byte-mode encoder, so these craft the corresponding inputs from the shared codeword pipeline
def _demo(payload, version, level):
    m = _blank(version)
    _type_info(m, level, 0)
    _map_data(m, _make_codewords(payload, version, level), 0)
    return _image(m)


def _numeric_payload(digits, version):
    cb = 10 if version < 10 else 12 if version < 27 else 14
    bits = [(0b0001 >> (3 - i)) & 1 for i in range(4)] + [(len(digits) >> (cb - 1 - i)) & 1 for i in range(cb)]
    for i in range(0, len(digits), 3):
        group = digits[i:i+3]
        n = {1: 4, 2: 7, 3: 10}[len(group)]
        bits += [(int(group) >> (n - 1 - j)) & 1 for j in range(n)]
    return bits


def _alpha_payload(text, version):
    cb = 9 if version < 10 else 11 if version < 27 else 13
    bits = [(0b0010 >> (3 - i)) & 1 for i in range(4)] + [(len(text) >> (cb - 1 - i)) & 1 for i in range(cb)]
    for i in range(0, len(text), 2):
        if i + 1 < len(text):
            v = _ALPHANUM.index(text[i]) * 45 + _ALPHANUM.index(text[i+1])
            bits += [(v >> (10 - j)) & 1 for j in range(11)]
        else:
            bits += [(_ALPHANUM.index(text[i]) >> (5 - j)) & 1 for j in range(6)]
    return bits


def _damaged(data, level, flips):
    grid = _encode(data, level)
    func = _function_map((len(grid) - 17) // 4)
    cells = [(r, c) for r in range(len(grid)) for c in range(len(grid)) if not func[r][c]]
    for r, c in cells[:flips]:
        grid[r][c] ^= 1
    return ensure_str(_image(grid))


def _bad_format(data, level):
    grid, valid = _encode(data, level), [_bch_format(d) for d in range(32)]
    raw = next(r for r in range(1 << 15) if min(bin(r ^ v).count("1") for v in valid) > 3)
    for i in range(15):
        grid[i if i < 6 else i + 1 if i < 8 else len(grid) - 15 + i][8] = (raw >> i) & 1
    return ensure_str(_image(grid))


