# GF(256) arithmetic (QR primitive polynomial x^8 + x^4 + x^3 + x^2 + 1)
_EXP, _LOG = [1] * 256, [0] * 256
for _i in range(8):
    _EXP[_i] = 1 << _i
for _i in range(8, 256):
    _EXP[_i] = _EXP[_i-4] ^ _EXP[_i-5] ^ _EXP[_i-6] ^ _EXP[_i-8]
for _i in range(255):
    _LOG[_EXP[_i]] = _i


def _gmul(a, b):
    return 0 if a == 0 or b == 0 else _EXP[(_LOG[a] + _LOG[b]) % 255]


def _ginv(a):
    return _EXP[(255 - _LOG[a]) % 255]


def _gdiv(a, b):
    return 0 if a == 0 else _gmul(a, _ginv(b))


def _gexp(n):
    return _EXP[n % 255]


