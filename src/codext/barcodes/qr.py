"""QR Code Codec - QR code content encoding.

This encodes the input as a real (standard, scannable) QR code, as opposed to the "fakeqr" codec which only mimics the
 aspect of one. It uses the byte mode, selects the smallest version (1 to 40) that fits the data for the chosen error
 correction level (L, M, Q or H, given in the codec name, e.g. "qr-h" ; M by default) and picks the data mask with the
 lowest penalty score. Decoding reads the QR code back, recovering its error correction level and mask from the format
 information and applying Reed-Solomon error correction, so that a damaged QR code can still be decoded.

By default, the QR code is a grayscale PNG image (one pixel per module), but the "-text" variant (e.g. "qr-text" or
 "qr-h-text") renders it as plain text instead, with a full block for a dark module and a space for a light one, rows
 separated by newlines. Decoding accepts either form, auto-detecting the image from its PNG signature. Decoding also
 handles the numeric and alphanumeric modes, so that QR codes generated by other tools can be read.

This codec:
- en/decodes strings from str to str
- en/decodes strings from bytes to bytes
- decodes file content to str (read)
- encodes file content from str to bytes (write)

Reference: https://en.wikipedia.org/wiki/QR_code (ISO/IEC 18004)
"""
