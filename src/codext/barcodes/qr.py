def _blocks(version, level):
    """ List of (total codewords, data codewords) per error correction block. """
    row, blocks = _RSB[(version - 1) * 4 + _EC_OFFSET[level]], []
    for i in range(0, len(row), 3):
        count, total, data = row[i:i+3]
        blocks += [(total, data)] * count
    return blocks


