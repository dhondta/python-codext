# Reed-Solomon and BCH codes
def _poly_mul(p, q):
    r = [0] * (len(p) + len(q) - 1)
    for i, a in enumerate(p):
        for j, c in enumerate(q):
            r[i+j] ^= _gmul(a, c)
    return r


def _poly_eval(p, x):
    y = p[0]
    for c in p[1:]:
        y = _gmul(y, x) ^ c
    return y


def _rs_ec(data, nec):
    """ Reed-Solomon error correction codewords for the given data codewords. """
    gen = [1]
    for i in range(nec):
        gen = _poly_mul(gen, [1, _gexp(i)])
    res = list(data) + [0] * nec
    for i in range(len(data)):
        coef = res[i]
        if coef != 0:
            for j in range(1, len(gen)):
                res[i+j] ^= _gmul(gen[j], coef)
    return res[len(data):]


def _rs_decode(msg, nec):
    """ Correct the errors of a Reed-Solomon codeword (data + error correction codewords) and return the result. """
    msg, synd = list(msg), [0]
    synd += [_poly_eval(msg, _gexp(i)) for i in range(nec)]
    if max(synd) == 0:
        return msg
    err_loc, old_loc = [1], [1]                                             # Berlekamp-Massey: error locator polynomial
    for i in range(nec):
        delta = synd[i+1]
        for j in range(1, len(err_loc)):
            delta ^= _gmul(err_loc[-(j+1)], synd[i+1-j])
        old_loc = old_loc + [0]
        if delta != 0:
            if len(old_loc) > len(err_loc):
                new_loc = [_gmul(c, delta) for c in old_loc]
                old_loc = [_gmul(c, _ginv(delta)) for c in err_loc]
                err_loc = new_loc
            err_loc = _poly_add(err_loc, [_gmul(c, delta) for c in old_loc])
    while err_loc and err_loc[0] == 0:
        err_loc.pop(0)  # pragma: no cover
    if (len(err_loc) - 1) * 2 > nec:
        raise QrDecodeError("'qr' codec can't decode too damaged input")
    rev = err_loc[::-1]                                                     # Chien search: error positions
    err_pos = [len(msg) - 1 - i for i in range(len(msg)) if _poly_eval(rev, _gexp(i)) == 0]
    if len(err_pos) != len(err_loc) - 1:
        raise QrDecodeError("'qr' codec can't decode too damaged input")
    msg = _correct_errata(msg, synd, err_pos)
    synd = [0] + [_poly_eval(msg, _gexp(i)) for i in range(nec)]
    if max(synd) > 0:  # pragma: no cover
        raise QrDecodeError("'qr' codec can't decode too damaged input")
    return msg


def _poly_add(p, q):
    r = [0] * max(len(p), len(q))
    for i in range(len(p)):
        r[i + len(r) - len(p)] = p[i]
    for i in range(len(q)):
        r[i + len(r) - len(q)] ^= q[i]
    return r


def _correct_errata(msg, synd, err_pos):
    """ Forney algorithm: compute and apply the error magnitudes at the given positions. """
    coef_pos = [len(msg) - 1 - p for p in err_pos]
    e_loc = [1]
    for i in coef_pos:
        e_loc = _poly_mul(e_loc, _poly_add([1], [_gexp(i), 0]))
    prod = _poly_mul(synd[::-1], e_loc)
    remainder = prod[len(prod)-len(e_loc):]                                 # (synd * errata locator) mod x^len(e_loc)
    x = [_gexp((-(255 - p)) % 255) for p in coef_pos]
    e = [0] * len(msg)
    for i, xi in enumerate(x):
        xi_inv, denom = _ginv(xi), 1
        for j in range(len(x)):
            if j != i:
                denom = _gmul(denom, 1 ^ _gmul(xi_inv, x[j]))
        y = _gmul(xi, _poly_eval(remainder, xi_inv))
        e[err_pos[i]] = _gdiv(y, denom)
    return _poly_add(msg, e)


def _bch(data, generator, degree, mask=0):
    d, glen = data << degree, generator.bit_length()
    while d.bit_length() >= glen:
        d ^= generator << (d.bit_length() - glen)
    return ((data << degree) | d) ^ mask


def _bch_format(data5):
    return _bch(data5, _G15, 10, _G15_MASK)


def _bch_version(version):
    return _bch(version, _G18, 12)


