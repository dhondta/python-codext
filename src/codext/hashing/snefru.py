def __sboxes():
    if not _SB:
        d = b64decode(SNEFRU_SBOXES)
        _SB.extend([int.from_bytes(d[4*(256*i+j):4*(256*i+j+1)], "big") for j in range(256)] for i in range(16))
    return _SB


def snefru(size="", passes=""):
    # bad parameters are only reported when coding, as the lookup of the bare codec name must succeed (e.g. when
    #  listing the encodings)
    size, passes = size or 128, passes or 8
    def _hash(data, errors="strict"):
        if size not in range(32, 481, 32):
            raise LookupError("Bad parameter for encoding 'snefru': digest size must be a multiple of 32 from 32 to "
                              "480")
        if passes not in range(2, 9):
            raise LookupError("Bad parameter for encoding 'snefru': number of passes must be from 2 to 8")
        sb, n = __sboxes(), size // 32
        # zero padding to a whole number of blocks (none for empty data), then a block ending with the length in bits
        d, bs = b(data), 64 - 4 * n
        d += b"\x00" * (-len(d) % bs + bs - 8) + (8 * len(d)).to_bytes(8, "big")
        h = [0] * n
        for i in range(0, len(d), bs):
            w = h + [int.from_bytes(d[i+j:i+j+4], "big") for j in range(0, bs, 4)]
            for p in range(passes):
                for r in (16, 8, 16, 24):
                    for k in range(16):
                        e = sb[2 * p + k // 2 % 2][w[k] & 0xff]
                        w[k - 1] ^= e
                        w[(k + 1) % 16] ^= e
                    w = [(x >> r | x << (32 - r)) & M32 for x in w]
            h = [x ^ w[15 - j] for j, x in enumerate(h)]
        return b"".join(x.to_bytes(4, "big") for x in h).hex(), len(data)
    return _hash


